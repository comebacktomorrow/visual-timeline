// Writes the fixture frames that nginx serves in the dev stack and e2e
// (tests/folder-fixture/frames/{host}/{YYYY}-{MM}-{DD}/{HH}{mm}{ss}_{variant}.svg,
// the HTTP folder of #125), and the same frames as other data sources hold
// them (M5): rows for PostgreSQL (postgres.sql) and log lines for Loki
// (loki-push.json), each pointing at nginx's copy of the image.
// Two hosts, a frame about every 3 minutes from 10:00 to 10:27 UTC on
// 2026-01-01, in a small (lo) and a large (hi) size. Seconds drift, as real
// uploads' do; cam-b misses 10:12 and 10:15. Run: node tests/folder-fixture/generate.mjs
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, 'frames');
// empty the folder, not remove it: the dev stack's nginx bind-mounts it, and a
// removed and recreated folder would leave nginx serving the deleted one
mkdirSync(root, { recursive: true });
for (const name of readdirSync(root)) {rmSync(join(root, name), { recursive: true, force: true });}
// where browsers load the images from (docker-compose.yaml publishes nginx on 8098)
const IMAGES = 'http://localhost:8098/html';
const rows = [];
const drift = [0, 7, 13, 4, 11, 2, 9, 15, 6, 1];
const hue = { 'cam-a': 160, 'cam-b': 10 };
for (const host of ['cam-a', 'cam-b']) {
  for (let k = 0; k < 10; k++) {
    if (host === 'cam-b' && (k === 4 || k === 5)) {continue;}
    const t = new Date(Date.UTC(2026, 0, 1, 10, k * 3, drift[k]));
    const hhmmss = t.toISOString().slice(11, 19).replace(/:/g, '');
    const dir = join(root, host, '2026-01-01');
    mkdirSync(dir, { recursive: true });
    const path = (v) => `${host}/2026-01-01/${hhmmss}_${v}.svg`;
    rows.push({ ts: t, host, image: `${IMAGES}/${path('lo')}`, hi: `${IMAGES}/${path('hi')}` });
    for (const [variant, w, h] of [['lo', 160, 90], ['hi', 640, 360]]) {
      const label = `${host} ${t.toISOString().slice(11, 19)}`;
      writeFileSync(join(dir, `${hhmmss}_${variant}.svg`),
        `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 160 90">` +
        `<rect width="160" height="90" fill="hsl(${hue[host]},45%,30%)"/>` +
        `<text x="80" y="52" text-anchor="middle" font-family="sans-serif" font-size="14" fill="#fff">${label}</text></svg>\n`);
    }
  }
}

// PostgreSQL: a table of frames and a table of states, as a site's own
// database might keep them; cam-b is under maintenance while it sends none
const q = (v) => `'${v}'`;
writeFileSync(join(here, 'postgres.sql'), [
  '-- Generated by generate.mjs: the fixture frames as rows (M5).',
  'CREATE TABLE frames (time timestamptz NOT NULL, host text NOT NULL, image text NOT NULL, image_hi text);',
  'CREATE TABLE states (time timestamptz NOT NULL, host text NOT NULL, state text);',
  ...rows.map((r) => `INSERT INTO frames VALUES (${q(r.ts.toISOString())}, ${q(r.host)}, ${q(r.image)}, ${q(r.hi)});`),
  "INSERT INTO states VALUES ('2026-01-01T10:10:30Z', 'cam-b', 'maintenance'), ('2026-01-01T10:16:30Z', 'cam-b', '');",
  '',
].join('\n'));

// Loki: one stream per host, each line the image's URL (a camera's upload log)
const streams = ['cam-a', 'cam-b'].map((host) => ({
  stream: { job: 'cameras', host },
  values: rows.filter((r) => r.host === host).map((r) => [String(r.ts.getTime() * 1e6), r.image]),
}));
writeFileSync(join(here, 'loki-push.json'), JSON.stringify({ streams }, null, 1) + '\n');
